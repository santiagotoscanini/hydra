// Bundles the dashboard into one file the hydra binary embeds
// (../cmd/hydra/dashboard.mjs), and notes a hash of what it was built from
// (../cmd/hydra/dashboard.sum) so `go test` can tell when the bundle is
// older than its sources. --check builds into memory and fails when the
// committed bundle differs from that build.

import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const out = join(here, "../cmd/hydra/dashboard.mjs");
const sumFile = join(here, "../cmd/hydra/dashboard.sum");

// What the bundle is made from. cmd/hydra/dashboard_test.go hashes the same
// files the same way.
function sources() {
	const files = ["build.mjs", "package.json", "package-lock.json", "tsconfig.json"];
	const walk = (dir) => {
		for (const name of readdirSync(join(here, dir)).sort()) {
			const rel = join(dir, name);
			if (statSync(join(here, rel)).isDirectory()) walk(rel);
			else files.push(rel);
		}
	};
	walk("src");
	return files.sort();
}

function sourceSum() {
	const h = createHash("sha256");
	for (const f of sources()) {
		h.update(f.split("\\").join("/") + "\0");
		h.update(readFileSync(join(here, f)));
		h.update("\0");
	}
	return h.digest("hex");
}

const result = await build({
	entryPoints: [join(here, "src/cli.tsx")],
	bundle: true,
	platform: "node",
	format: "esm",
	target: "node20",
	minify: true,
	legalComments: "none",
	write: false,
	define: { "process.env.NODE_ENV": '"production"' },
	// Ink loads React's devtools only when DEV=true: a stub stands in.
	plugins: [
		{
			name: "no-devtools",
			setup(b) {
				b.onResolve({ filter: /^react-devtools-core$/ }, () => ({ path: "devtools", namespace: "stub" }));
				b.onLoad({ filter: /.*/, namespace: "stub" }, () => ({
					contents: "export default { initialize() {}, connectToDevTools() {} };",
				}));
			},
		},
	],
	// Some of Ink's dependencies are CommonJS and call require().
	banner: {
		js: "// Generated by tui/build.mjs from tui/src. Do not edit.\nimport { createRequire as __hydraRequire } from 'node:module'; const require = __hydraRequire(import.meta.url);",
	},
	logLevel: "warning",
});
const code = result.outputFiles[0].contents;
const sum = sourceSum() + "\n";

if (process.argv.includes("--check")) {
	const have = readFileSync(out);
	const haveSum = readFileSync(sumFile, "utf8");
	if (!Buffer.from(code).equals(have) || haveSum !== sum) {
		console.error(`${relative(process.cwd(), out)} isn't what tui/src builds to: run \`npm run build\` in tui/ and commit the result`);
		process.exit(1);
	}
	console.log("the committed dashboard bundle matches its sources");
} else {
	writeFileSync(out, code);
	writeFileSync(sumFile, sum);
	console.log(`wrote ${relative(process.cwd(), out)} (${Math.round(code.length / 1024)} KB)`);
}
