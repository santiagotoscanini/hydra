// The dashboard is built from tui/ into dashboard.mjs, which is committed
// so that go build needs no npm. dashboard.sum is a hash of what it was
// built from, taken the way tui/build.mjs takes it: a change to tui/src
// without `npm run build` fails here. (CI also rebuilds it and compares.)
func TestDashboardBundleIsBuiltFromTheSources(t *testing.T) {
	tui := filepath.Join("..", "..", "tui")
	files := []string{"build.mjs", "package.json", "package-lock.json", "tsconfig.json"}
	err := filepath.WalkDir(filepath.Join(tui, "src"), func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(tui, path)
		files = append(files, filepath.ToSlash(rel))
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(files)
	h := sha256.New()
	for _, f := range files {
		data, err := os.ReadFile(filepath.Join(tui, f))
		if err != nil {
			t.Fatal(err)
		}
		h.Write([]byte(f + "\x00"))
		h.Write(data)
		h.Write([]byte{0})
	}
	want, err := os.ReadFile("dashboard.sum")
	if err != nil {
		t.Fatal(err)
	}
	if got := hex.EncodeToString(h.Sum(nil)); got != strings.TrimSpace(string(want)) {
		t.Fatalf("cmd/hydra/dashboard.mjs is older than tui/: run `npm run build` in tui/ (or make build) and commit both files")
	}
	if !bytes.HasPrefix(dashboardJS, []byte("// Generated by tui/build.mjs")) {
		t.Fatalf("the embedded dashboard isn't the bundle: %.60q", dashboardJS)
	}
}

func TestDashboardIsWrittenToTheCacheOnce(t *testing.T) {
	t.Setenv("HYDRA_CACHE_DIR", t.TempDir())
	a, err := dashboardScript()
	if err != nil {
		t.Fatal(err)
	}
	info, _ := os.Stat(a)
	b, err := dashboardScript()
	if err != nil || a != b {
		t.Fatalf("second call: %q, %v (first %q)", b, err, a)
	}
	if again, _ := os.Stat(b); !again.ModTime().Equal(info.ModTime()) {
		t.Errorf("written again although it was there")
	}
	if data, _ := os.ReadFile(a); !bytes.Equal(data, dashboardJS) {
		t.Errorf("the cached copy differs from the embedded one")
	}
	// A copy that got damaged is written again.
	os.WriteFile(a, []byte("broken"), 0o644)
	if _, err := dashboardScript(); err != nil {
		t.Fatal(err)
	}
	if data, _ := os.ReadFile(a); !bytes.Equal(data, dashboardJS) {
		t.Errorf("a damaged copy was kept")
	}
}

// The bundle loads in node: every module it imports resolves. Without a
// terminal it stops right after, and says why.
func TestDashboardBundleLoads(t *testing.T) {
	node, err := exec.LookPath("node")
	if err != nil {
		t.Skip("node isn't installed")
	}
	t.Setenv("HYDRA_CACHE_DIR", t.TempDir())
	script, err := dashboardScript()
	if err != nil {
		t.Fatal(err)
	}
	out, err := exec.Command(node, script).CombinedOutput()
	if code := nodeExit(err); code != 2 || !strings.Contains(string(out), "needs a terminal") {
		t.Fatalf("node %s: exit %d\n%s", script, code, out)
	}
}

func nodeExit(err error) int {
	if err == nil {
		return 0
	}
	if e, ok := err.(*exec.ExitError); ok {
		return e.ExitCode()
	}
	return -1
}

// Only a person at a terminal gets the dashboard; arguments, or no
// terminal (an agent, a script), keep what bare hydra always did.
func TestBareHydraOpensTheDashboardOnlyAtATerminal(t *testing.T) {
	if wantsDashboard([]string{"up", "-D"}) {
		t.Error("hydra up -D opened the dashboard")
	}
	if isTerminal(os.Stdin) && isTerminal(os.Stdout) {
		t.Skip("the test runs at a terminal")
	}
	if wantsDashboard(nil) {
		t.Error("bare hydra without a terminal opened the dashboard")
	}
}
