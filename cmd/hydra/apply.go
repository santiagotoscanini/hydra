package main

import (
	"fmt"
	"reflect"

	"gopkg.in/yaml.v3"
)

// applyProject hands a running process-compose the file a new plan renders
// to. current is the file its project runs now, at path out.
//
// process-compose applies an update in no particular order: it adds the new
// processes and replaces the changed ones as it comes across them, and a
// process whose dependency isn't in the project yet, or is still the old
// one, starts without waiting. A worker would start before the step that
// makes its Temporal namespace; a service, before the database it reads has
// its tables.
//
// So the file goes in steps (updateSteps): each process finds what it waits
// for already in the project, and waits for it the way the stack file says.
// When a step fails the file on disk is left at the last one that went
// through, so the next try carries on from what really runs.
func applyProject(out string, current, next []byte, update func(file string) error) error {
	applied := current
	for _, file := range updateSteps(current, next) {
		if err := writeFile(out, file); err != nil {
			return err
		}
		if err := update(out); err != nil {
			if applied != nil {
				writeFile(out, applied)
			}
			return err
		}
		applied = file
	}
	return nil
}

// updateSteps splits an update into the files to hand over, in order. The
// first holds, on top of what runs now, what changed and waits for nothing
// else that changed; the next adds what waits for those; and so on. The last
// is next itself, which also drops what is gone.
//
// hydra-watch only changes with the last one: it applies updates itself, and
// a new watcher that came up halfway would start on the same steps.
func updateSteps(current, next []byte) [][]byte {
	whole := [][]byte{next}
	var cur, nxt map[string]any
	if yaml.Unmarshal(current, &cur) != nil || yaml.Unmarshal(next, &nxt) != nil {
		return whole
	}
	was, _ := cur["processes"].(map[string]any)
	will, _ := nxt["processes"].(map[string]any)
	if len(was) == 0 || len(will) == 0 {
		return whole
	}
	changed := changedProcesses(was, will)
	delete(changed, "hydra-watch")

	// How many changed processes deep each one's dependencies go.
	depth := map[string]int{}
	var measure func(name string, path map[string]bool) int
	measure = func(name string, path map[string]bool) int {
		if d, ok := depth[name]; ok {
			return d
		}
		if path[name] {
			return 0 // a cycle; process-compose says so itself
		}
		path[name] = true
		d := 0
		proc, _ := will[name].(map[string]any)
		deps, _ := proc["depends_on"].(map[string]any)
		for dep := range deps {
			if changed[dep] {
				d = max(d, measure(dep, path)+1)
			}
		}
		delete(path, name)
		depth[name] = d
		return d
	}
	deepest := 0
	for name := range changed {
		deepest = max(deepest, measure(name, map[string]bool{}))
	}

	var steps [][]byte
	for level := 0; level < deepest; level++ {
		procs := map[string]any{}
		for name, def := range was {
			procs[name] = def
		}
		for name := range changed {
			if depth[name] <= level {
				procs[name] = will[name]
			}
		}
		doc := map[string]any{}
		for k, v := range nxt {
			doc[k] = v
		}
		doc["processes"] = procs
		body, err := yaml.Marshal(doc)
		if err != nil {
			return whole
		}
		header := fmt.Sprintf("# Generated by hydra: step %d of %d of an update. Do not edit.\n", level+1, deepest+1)
		steps = append(steps, append([]byte(header), body...))
	}
	return append(steps, next)
}

// changedProcesses names the processes of will that was doesn't have, or
// defines differently.
func changedProcesses(was, will map[string]any) map[string]bool {
	out := map[string]bool{}
	for name, def := range will {
		if old, ok := was[name]; !ok || !reflect.DeepEqual(old, def) {
			out[name] = true
		}
	}
	return out
}

// processesOf reads the processes of a rendered file.
func processesOf(file []byte) map[string]any {
	var doc map[string]any
	if yaml.Unmarshal(file, &doc) != nil {
		return nil
	}
	procs, _ := doc["processes"].(map[string]any)
	return procs
}
